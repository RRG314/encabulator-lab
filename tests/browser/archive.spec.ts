import { expect, test } from '@playwright/test'

test('distinguishes the TE-01 bench from the photographed GE configuration',async({page})=>{
  await page.goto('./#/explorer')
  await expect(page.getByText(/Bench-scale engineering design/)).toBeVisible()
  const references=page.getByRole('navigation',{name:'Historical Turbo Encabulator configurations'})
  await expect(references.getByRole('link',{name:/Quick/})).toHaveAttribute('href','#/archive/quick-1944')
  await references.getByRole('link',{name:/General Electric/}).click()
  await expect(page.getByRole('heading',{name:'General Electric Turboencabulator GE-62'})).toBeVisible()
  await expect(page.getByRole('link',{name:/1962 catalog photograph/})).toHaveAttribute('href',/GE_Turboencabulator_pg_1/)
  await expect(page.getByText('CAD SCHEMATIC',{exact:true})).toBeVisible({timeout:15000})
  await expect(page.getByRole('heading',{name:'Pentametric fan',level:3})).toBeVisible()
})

test('filters the archive, opens independent Magneto CAD, and traces parts to drawings',async({page})=>{
  test.setTimeout(60000)
  await page.goto('./#/archive')
  await expect(page.getByRole('heading',{name:'Encabulator Technical Archive'})).toBeVisible()
  await page.getByRole('searchbox',{name:'Search archive'}).fill('satellite magnet')
  await expect(page.getByRole('link',{name:'Magneto-Turboencabulator'})).toBeVisible()
  await expect(page.getByRole('link',{name:'Micro Encabulator',exact:true})).toHaveCount(0)
  await page.getByRole('link',{name:'Magneto-Turboencabulator',exact:true}).click()
  await page.getByRole('link',{name:'Assembly workbench'}).click()
  await expect(page.getByText('CAD SCHEMATIC',{exact:true})).toBeVisible({timeout:20000})
  await page.getByRole('searchbox',{name:'Search components'}).fill('MT-005')
  await page.getByRole('button',{name:/Satellite magnet disk/,exact:false}).filter({hasNot:page.locator('svg')}).first().click()
  await page.getByRole('button',{name:'100% · Exploded',exact:true}).click()
  await expect(page.getByRole('slider',{name:'Exploded distance'})).toHaveValue('100')
  await page.getByRole('link',{name:'Engineering record'}).click()
  await expect(page.getByRole('heading',{name:'Satellite magnet disk',exact:true,level:1})).toBeVisible()
  const path=await page.getByRole('link',{name:'Dimensioned schematic SVG'}).getAttribute('href')
  const result=await page.request.get(new URL(path!,page.url()).href)
  expect(result.ok()).toBe(true)
  expect(await result.text()).toContain('MT-005')
  await page.getByRole('link',{name:'Operating study'}).click()
  await expect(page.getByRole('img',{name:/plot of Shaft speeds/})).toBeVisible()
  await page.getByRole('button',{name:'Single step'}).click()
  await page.getByRole('button',{name:'Motion replay'}).click()
  await expect(page.getByText('CAD SCHEMATIC',{exact:true})).toBeVisible({timeout:20000})
  await expect(page.getByText(/^SIMULATION · .* rpm ·/)).toBeVisible()
})

test('runs a computational study without mechanical controls and checks narrow layouts',async({page})=>{
  await page.setViewportSize({width:340,height:820})
  await page.goto('./#/archive/hyper-2022/study')
  await expect(page.getByRole('heading',{name:'SANS ICS HyperEncabulator'})).toBeVisible()
  await page.getByRole('checkbox',{name:'Inject operating disturbance'}).check()
  await page.getByRole('slider',{name:'Time',exact:true}).press('End')
  await expect(page.getByText('Controlled shutdown',{exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'Assembly workbench'})).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(340)
  await page.goto('./#/me01/installation')
  await page.getByRole('combobox',{name:'External load model'}).selectOption('pump')
  await expect(page.getByRole('heading',{name:'Liquid-side pump boundary'})).toBeVisible()
  await expect(page.getByRole('img',{name:/plot of Host shaft response/})).toBeVisible()
})

test('compares three registered assemblies with shared orientation and separation',async({page})=>{
  test.setTimeout(60000)
  await page.goto('./#/comparison')
  await page.getByRole('combobox',{name:'Configuration 3'}).selectOption('electro-2021')
  await expect(page.getByRole('heading',{name:/Electro Turbo Encabulator ET-21/})).toBeVisible()
  await page.getByRole('slider',{name:'Shared separation'}).press('End')
  await expect(page.getByRole('slider',{name:'Shared separation'})).toHaveValue('100')
  await page.getByRole('group',{name:'Shared camera orientation'}).getByRole('button',{name:'Top'}).click()
  await expect(page.getByRole('group',{name:'Shared camera orientation'}).getByRole('button',{name:'Top'})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByText('CAD schematic',{exact:true})).toHaveCount(3,{timeout:20000})
})
