test('operates the main shaft against an adjustable fixture while the enclosure is transparent',async({page})=>{
  await page.goto('./#/simulation')
  await expect(page.getByText('CAD SCHEMATIC',{exact:true})).toBeVisible({timeout:20000})
  await page.getByRole('combobox',{name:'Connected test fixture'}).selectOption('generator')
  await page.getByRole('combobox',{name:'Simulation speed'}).selectOption('0.25')
  const xray=page.getByRole('button',{name:'X-ray enclosure'})
  await xray.click()
  const rotor=page.getByTestId('fixture-rotor')
  const ready=await rotor.getAttribute('transform')
  await page.getByRole('button',{name:'Start drive'}).click()
  await expect(rotor).not.toHaveAttribute('transform',ready!)
  await expect(xray).toHaveAttribute('aria-pressed','true')
  await page.getByRole('slider',{name:'Reference load torque'}).press('End')
  await expect(page.getByRole('slider',{name:'Reference load torque'})).toHaveValue('0.16')
  await page.getByRole('button',{name:'Inject guard fault'}).click()
  await expect(page.getByRole('region',{name:'Interactive dynamometer'}).getByRole('status')).toHaveText('Fault-latched · Guard open')
})
